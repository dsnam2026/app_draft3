def page_report():
    op_screen("report", OP["report"])
    st.header("📊 학습 리포트")
    prog, lg = db.progress(U), db.logs(U)
    tot, ok = sum(l["total"] for l in lg), sum(l["correct"] for l in lg)
    days = sorted({l["day"] for l in lg}, reverse=True)
    streak, d = 0, date.today()
    while str(d) in days or (streak == 0 and str(d - pd.Timedelta(days=1)) in days):
        if str(d) in days:
            streak += 1
        d -= pd.Timedelta(days=1)
    c = st.columns(4)
    c[0].metric("배운 단어", f"{len(prog)} / {len(W)}")
    c[1].metric("전체 정답률", f"{round(100 * ok / tot) if tot else 0}%")
    c[2].metric("연속 학습일", f"{streak}일")
    c[3].metric("총 학습 시간", f"{round(sum(l['secs'] for l in lg) / 60)}분")
    st.subheader("단계별 학습 현황")
    for lv, name in LEVELS.items():
        n = sum(1 for w in LEVEL_WORDS[lv] if w in prog)
        st.progress(n / len(LEVEL_WORDS[lv]), text=f"{name}: {n} / {len(LEVEL_WORDS[lv])}")
    if lg:
        df = pd.DataFrame(lg)
        df["wrong"] = df["total"] - df["correct"]
        st.subheader("날짜별 문제 수")
        st.bar_chart(df.groupby("day")[["correct", "wrong"]].sum().rename(columns={"correct": "정답", "wrong": "오답"}))
        st.subheader("활동 종류별")
        k = df.groupby("kind")[["total", "correct"]].sum()
        k.index = [KINDS.get(i, i) for i in k.index]
        st.dataframe(k.rename(columns={"total": "문제 수", "correct": "정답 수"}))
    st.subheader("복습 상자 분포")
    st.bar_chart(pd.Series({f"상자 {b}": sum(1 for p in prog.values() if p["box"] == b) for b in range(1, 6)}))
    ms = db.missed(U)
    if ms:
        st.subheader("자주 틀리는 단어")
        st.dataframe(pd.DataFrame([dict(단어=m["word"], 뜻=W[m["word"]]["k"], 틀린횟수=m["n"], 마지막=m["last"]) for m in ms[:10]]),
                     hide_index=True)
    if prog:
        out = pd.DataFrame([dict(word=w, meaning=W[w]["k"], level=W[w]["level"], box=p["box"], due=p["due"],
                                 right=p["right"], wrong=p["wrong"]) for w, p in prog.items()])
        st.download_button("진행 상황 CSV 내려받기", out.to_csv(index=False).encode("utf-8-sig"), "progress.csv", "text/csv")



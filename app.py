# ------------------------------------------------------------------ word selection helpers
def interferes(a, b):
    """Blueprint §2: don't put look-alike or same-meaning words in the same set."""
    return (W[a]["k"] == W[b]["k"] or difflib.SequenceMatcher(None, a.lower(), b.lower()).ratio() >= 0.75)


def pick_new(level, n, prog):
    levels = [level] if level in LEVELS else list(LEVELS)
    cand = [w for lv in levels for w in random.sample(LEVEL_WORDS[lv], len(LEVEL_WORDS[lv])) if w not in prog]
    if level not in LEVELS:  # auto: easiest tier that still has unlearned words
        for lv in LEVELS:
            c = [w for w in cand if W[w]["level"] == lv]
            if c:
                cand = c
                break
    out = []
    for w in cand:
        if all(not interferes(w, x) for x in out):
            out.append(w)
        if len(out) == n:
            break
    return out


def make_options(word):
    t, ds, seen = W[word], [], {W[word]["k"]}
    for x in random.sample(LEVEL_WORDS[t["level"]], 80):
        if x != word and W[x]["k"] not in seen:
            ds.append(x)
            seen.add(W[x]["k"])
        if len(ds) == 3:
            break
    o = [word] + ds
    random.shuffle(o)
    return o


# ------------------------------------------------------------------ lesson engine (resumable)
def commit():
    if ss.lesson and ss.lesson["phase"] != "done":
        db.kv_set(U, "lesson", ss.lesson)


def start_lesson(kind, words, level=None):
    ladder = LADDERS[S["goal"]]
    prog = db.progress(U)
    L = dict(kind=kind, level=level, words=words, ladder=ladder, phase="intro" if kind == "new" else "quiz",
             intro_i=0, pending=[], nxt=[], round=1, qn=0, cur=None, tot=0, ok=0, slip={}, done=[], last=None,
             secs=0.0, rewarded=False, started=time.strftime("%Y-%m-%d %H:%M"))
    if kind != "new":
        for w in words:
            si = min(prog[w]["box"] - 1, len(ladder) - 1) if kind == "review" else 0
            last = si if kind == "review" else min(1, len(ladder) - 1)
            L["pending"].append([w, si, last])
        random.shuffle(L["pending"])
    ss.lesson, ss.nav = L, "lesson"
    if kind != "new":
        advance()
    commit()


def begin_quiz(L):
    order = L["words"][:]
    random.shuffle(order)
    tail = set(L["words"][-3:])  # last words just shown are tested late -> retrieval from long-term memory
    if len(order) > 6:
        order = [w for w in order if w not in tail] + [w for w in order if w in tail]
    L["pending"] = [[w, 0, len(L["ladder"]) - 1] for w in order]
    L["phase"] = "quiz"
    advance()


def advance():
    L = ss.lesson
    if not L["pending"]:
        if not L["nxt"]:
            return finish(L)
        nxt = L["nxt"]
        random.shuffle(nxt)  # shuffle every round (no serial learning)
        if len(nxt) > 1 and nxt[0][0] == L["last"]:
            nxt.append(nxt.pop(0))
        L["pending"], L["nxt"] = nxt, []
        L["round"] += 1
    w, si, last = L["pending"].pop(0)
    step = L["ladder"][si]
    L["qn"] += 1
    L["cur"] = dict(w=w, si=si, last=last, step=step, opts=make_options(w) if step in ("REC", "PREC", "LIS") else [],
                    fb=None, rev=False, qn=L["qn"], t0=time.time())


def answer(ok, given=""):
    L = ss.lesson
    c = L["cur"]
    w = c["w"]
    L["tot"] += 1
    L["ok"] += int(ok)
    L["secs"] += min(60.0, time.time() - c["t0"])
    if ok:
        if c["si"] >= c["last"]:  # drop-out: finished the ladder for this word
            L["done"].append(w)
            word_done(L, w)
        else:
            L["nxt"].append([w, c["si"] + 1, c["last"]])
    else:
        L["slip"][w] = 1
        db.add_missed(U, w)
        L["nxt"].append([w, c["si"], c["last"]])  # comes back later in a shuffled round
    L["last"] = w
    if ok:
        st.toast("✅ 정답!")
        advance()
    else:
        c["fb"] = dict(given=given)
    commit()
    st.rerun()


def word_done(L, w):
    if L["kind"] == "new":
        db.mark_learned(U, w)
    elif L["kind"] == "review":
        db.review_result(U, w, w not in L["slip"])
    elif L["kind"] == "missed" and w not in L["slip"]:
        db.clear_missed(U, w)


def finish(L):
    L["phase"], L["cur"] = "done", None
    if not L["rewarded"]:
        L["rewarded"] = True
        db.log(U, L["kind"], L["tot"], L["ok"], L["secs"])
        db.kv_del(U, "lesson")
        reward(KINDS[L["kind"]])
        op(OP["done"])



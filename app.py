def _s_mark_learned(user, word):
    """Word finished its first session -> box 1, first review tomorrow (~24h, blueprint 4-2)."""
    today = date.today()
    with _c() as c:
        c.execute("""INSERT INTO progress(username,word,box,due,learned) VALUES(?,?,1,?,?)
                     ON CONFLICT(username,word) DO UPDATE SET box=1, due=excluded.due""",
                  (user, word, str(today + timedelta(days=BOX_DAYS[1])), str(today)))


def _s_review_result(user, word, ok):
    with _c() as c:
        r = c.execute("SELECT box FROM progress WHERE username=? AND word=?", (user, word)).fetchone()
        if not r:
            return
        box = min(r["box"] + 1, 5) if ok else 1
        due = date.today() + timedelta(days=BOX_DAYS[box])
        c.execute(f"UPDATE progress SET box=?, due=?, {'right' if ok else 'wrong'}={'right' if ok else 'wrong'}+1 "
                  "WHERE username=? AND word=?", (box, str(due), user, word))


def _s_count_answer(user, word, ok):
    col = "right" if ok else "wrong"
    with _c() as c:
        c.execute(f"UPDATE progress SET {col}={col}+1 WHERE username=? AND word=?", (user, word))



def make_options(word):
    t, ds, seen = W[word], [], {W[word]["k"]}
    pool = LEVEL_WORDS[t["level"]]
    for x in random.sample(pool, min(len(pool), 150)):
        if x == word or W[x]["k"] in seen:
            continue
        if difflib.SequenceMatcher(None, x.lower(), word.lower()).ratio() >= 0.8:
            continue
        ds.append(x)
        seen.add(W[x]["k"])
        if len(ds) == 3:
            break
    opts = [word] + ds
    random.shuffle(opts)
    return opts


def new_question(qz):
    w = qz["order"][qz["i"]]
    qz["q"] = dict(w=w, opts=make_options(w), wrong=[], status=None)



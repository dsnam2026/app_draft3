def guess_pos(w, k):
    lw = w.lower()
    if lw in POS_FIX:
        return POS_FIX[lw]
    if lw in _CLOSED:
        return _CLOSED[lw]
    if k.endswith("다"):
        return "v"
    if k.endswith(_ADJ_END):
        return "adj"
    if lw.endswith("ly") and k.endswith(("히", "게", "이", "로")):
        return "adv"
    return "n"


def _load():
    pack = json.loads(zlib.decompress(base64.b64decode(_PACK)).decode("utf-8"))
    ex = {k.lower(): list(v) for k, v in pack["examples"].items()}
    for k, v in EXTRA_EXAMPLES.items():
        ex[k.lower()] = [v] if isinstance(v, str) else list(v)
    words = {}
    for w, lv, k, var in pack["words"]:
        words[w] = dict(w=w, level=lv, k=k, var=var, pos=guess_pos(w, k))
    return words, ex



def _secret(name):
    v = os.environ.get(name)
    if v:
        return v
    try:
        return st.secrets.get(name)
    except Exception:
        return None


def _gen_examples(words):
    key = _secret("ANTHROPIC_API_KEY")
    if not key or not words:
        return {}
    lines = "\n".join(f"- {w} ({W[w]['k']})" for w in words)
    prompt = ("For each English word below, write 2 short, natural example sentences (8-14 words each) for a Korean "
              "middle-school learner. Use the word in the meaning given in parentheses. Reply with JSON only, no "
              'markdown: {"word": ["sentence 1", "sentence 2"], ...}\n\nWords:\n' + lines)
    body = json.dumps({"model": _secret("ANTHROPIC_MODEL") or "claude-haiku-5-5", "max_tokens": 3000,
                       "messages": [{"role": "user", "content": prompt}]}).encode()
    req = urllib.request.Request("https://api.anthropic.com/v1/messages", data=body, headers={
        "content-type": "application/json", "x-api-key": key, "anthropic-version": "2023-06-01"})
    with urllib.request.urlopen(req, timeout=60) as r:
        data = json.load(r)
    text = "".join(b.get("text", "") for b in data.get("content", []))
    obj = json.loads(text[text.index("{"): text.rindex("}") + 1])
    out = {}
    for w in words:
        v = obj.get(w)
        if isinstance(v, list) and all(isinstance(s, str) for s in v) and v:
            out[w] = [s.strip() for s in v[:2]]
    return out


def ensure_examples(words):
    """Fill missing example sentences for a set (one API call per 25 words, only if a key is configured)."""
    tried = st.session_state.setdefault("ex_tried", set())
    cached = db_ex_get(words)
    missing = [w for w in words if not EXAMPLES.get(w.lower()) and w not in cached and w not in tried]
    if not missing or not _secret("ANTHROPIC_API_KEY"):
        return
    with st.spinner("예문을 준비하고 있어요…"):
        for i in range(0, len(missing), 25):
            chunk = missing[i:i + 25]
            tried.update(chunk)
            try:
                for w, s in _gen_examples(chunk).items():
                    db_ex_put(w, s)
            except Exception:
                pass


def examples_for(w):
    return EXAMPLES.get(w.lower()) or db_ex_get([w]).get(w, [])


